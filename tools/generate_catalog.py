#!/usr/bin/env python3
"""Build the directory catalog from pinned upstream metadata and this overlay.

Usage: python3 tools/generate_catalog.py upstream/patches-list.json [--check]
The runtime bundle is the source of truth; this file is discovery metadata.
"""
import argparse
import copy
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("upstream", type=Path)
parser.add_argument("--check", action="store_true")
args = parser.parse_args()
data = json.loads(args.upstream.read_text(encoding="utf-8"))
if data["version"] != "2.2.0":
    raise SystemExit("Expected the pinned upstream v2.2.0 catalog")
packages = next(p["compatiblePackages"] for p in data["patches"]
                if p["name"] == "Playback speed" and any(
                    v["packageName"] == "com.google.android.youtube"
                    for v in p.get("compatiblePackages", [])))
patch = {
    "name": "YouTube Censor",
    "description": "Mutes caption-timed profanity and optionally masks subtitle text locally. Requires a caption track.",
    "default": True,
    "category": None,
    "compatiblePackages": copy.deepcopy(packages),
    "options": [],
}
if any(p["name"] == patch["name"] for p in data["patches"]):
    raise SystemExit("The upstream catalog already contains this overlay name")
data["patches"].append(patch)
data["patches"].sort(key=lambda p: p["name"].casefold())
data["version"] = "0.8.1"
data["NOTE"] = "Generated by tools/generate_catalog.py from pinned Morphe v2.2.0 plus the YouTube Censor overlay. Do not edit by hand."
output = json.dumps(data, indent=2, ensure_ascii=False) + "\n"
target = ROOT / "patches-list.json"
if args.check:
    if target.read_text(encoding="utf-8") != output:
        raise SystemExit("Discovery catalog is out of date")
    print("Discovery catalog matches the pinned upstream and overlay")
else:
    target.write_text(output, encoding="utf-8", newline="\n")
    print("Wrote", target)
